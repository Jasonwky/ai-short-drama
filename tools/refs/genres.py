# -*- coding: utf-8 -*-
"""拆解卡自己的宽题材闭集(spec 2.2):含 `premise.DIMS["genre"]` 的全部取值,外加网文 / 短剧常见的大类;
每个取值标明对应 `premise.DIMS["genre"]` 的哪一个(最接近的那个,对不上的归「其他」)。`premise.DIMS` 不动。

`tag_group`:平台标签 → 题材,冷门对照分组用(冷门作品只做第一层,没有 LLM 给的题材)。认不出返回 None,不猜。
"""
from __future__ import annotations

from tools.llm.premise import DIMS

TO_PREMISE: dict[str, str] = {
    **{g: g for g in DIMS["genre"] if g != "其他"},
    "玄幻": "其他",
    "仙侠": "其他",
    "科幻": "其他",
    "无限流": "其他",
    "末世": "其他",
    "宫斗宅斗": "古装权谋",
    "种田": "其他",
    "校园青春": "都市情感",
    "豪门": "都市情感",
    "年代": "家庭伦理",
    "悬疑推理": "悬疑",
    "刑侦": "悬疑",
    "其他": "其他",
}
GENRES: tuple[str, ...] = tuple(TO_PREMISE)

# 关键词表:按顺序取第一条命中的(某个标签含任一关键词即命中);越具体的排在前面(「修仙 + 重生」归仙侠)。
# 「古代」「爱情」「逼婚」这类单看分不出题材的不收。
TAG_RULES: tuple[tuple[tuple[str, ...], str], ...] = (
    (("无限流",), "无限流"),
    (("末世", "丧尸", "废土"), "末世"),
    (("科幻", "星际", "机甲"), "科幻"),
    (("仙侠", "修仙", "修真"), "仙侠"),
    (("玄幻", "奇幻"), "玄幻"),
    (("刑侦", "破案"), "刑侦"),
    (("推理", "侦探"), "悬疑推理"),
    (("悬疑", "惊悚"), "悬疑"),
    (("宫斗", "宅斗"), "宫斗宅斗"),
    (("种田",), "种田"),
    (("重生", "复仇"), "重生复仇"),
    (("年代",), "年代"),
    (("校园", "青春"), "校园青春"),
    (("豪门", "总裁"), "豪门"),
    (("家庭", "伦理", "婆媳"), "家庭伦理"),
    (("权谋", "朝堂"), "古装权谋"),
    (("古风爱情", "古装爱情", "古代言情", "古言", "古装甜宠"), "古装甜宠"),
    (("逆袭", "赘婿", "战神"), "都市逆袭"),
    (("都市爱情", "都市情感", "现代言情", "现言", "婚恋"), "都市情感"),
)


def tag_group(source: str, tags: list[str]) -> str | None:
    """平台标签 → 题材;认不出返回 None(冷门对照里这类作品不进分组)。各平台目前共用一张关键词表,source 留给以后按平台分表。"""
    for words, genre in TAG_RULES:
        if any(w in t for t in tags for w in words):
            return genre
    return None
